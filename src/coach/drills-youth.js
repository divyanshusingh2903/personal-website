// A row of players, one ball each, evenly spaced down a line.
const column = (n, x, y0, dy, t = "a", prefix = t) =>
  Array.from({ length: n }, (_, i) => ({ id: `${prefix}${i + 1}`, t, x, y: y0 + dy * i }));

