// Ball Mastery Circuit: four players, each in their own coned box.
const BOX_X = [2.6, 7.4, 12.2, 17];
const BOX_Y = 3.6;
const boxCones = BOX_X.flatMap((cx) => [
  [cx - 1.8, BOX_Y - 1.8], [cx + 1.8, BOX_Y - 1.8], [cx - 1.8, BOX_Y + 1.8], [cx + 1.8, BOX_Y + 1.8],
]);
const eachBox = (fn) => Object.fromEntries(BOX_X.map((cx, i) => [`a${i + 1}`, fn(cx, BOX_Y)]));
const boxPlayers = (fn) => BOX_X.map((cx, i) => {
  const [x, y] = fn(cx, BOX_Y);
  return { id: `a${i + 1}`, t: "a", x, y };
});
const boxDiagram = (start, frames, note) => ({
  field: { type: "grid", w: 19.6, h: 7.2 },
  cones: boxCones,
  players: [{ id: "c", t: "c", x: 9.8, y: 0.5 }, ...boxPlayers(start)],
  balls: { b1: "a1", b2: "a2", b3: "a3", b4: "a4" },
  note,
  frames: frames.map(([fn, text]) => ({ note: text, move: eachBox(fn) })),
});

