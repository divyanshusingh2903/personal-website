/*
 * Drill library.
 *
 * Diagram coordinates are metres. x runs left → right, y runs top → bottom.
 *   field.type "grid"  a coned area of w × h
 *   field.type "half"  half pitch, 52.5 × 68, attacking goal on the right (x = 52.5)
 *   field.type "full"  full pitch, 105 × 68
 *   field.crop         [x0, y0, x1, y1] to zoom into part of a pitch
 *
 * Player team codes: a = coached team (lime bibs), b = opponents, n = neutral,
 * gk = goalkeeper, c = coach / server.
 *
 * Each frame lists players that move and where the ball goes. Arrows are
 * derived automatically: ball changes feet → pass, player moves with the ball
 * → dribble, player moves without it → run. `kind: "shot"` and `arc: true`
 * change how the ball's flight is drawn.
 */

